// Generates src/schema_sql.js from migrations/*.sql so the Worker can apply
// the same idempotent statements on its first request. Run by `npm run build`.
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export function splitSql(text) {
  return String(text)
    .split('\n')
    .filter((line) => !/^\s*--/.test(line))
    .join('\n')
    .split(/;\s*(?:\n|$)/)
    .map((s) => s.trim())
    .filter(Boolean)
}

export function readMigrations() {
  const dir = path.join(root, 'migrations')
  return fs.readdirSync(dir)
    .filter((f) => /^\d{4}_.+\.sql$/.test(f))
    .sort()
    .map((f) => ({ version: Number.parseInt(f.slice(0, 4), 10), file: f, statements: splitSql(fs.readFileSync(path.join(dir, f), 'utf8')) }))
    .filter((m) => m.version >= 2)
}

export function renderSchemaModule(migrations) {
  return '// GENERATED by scripts/build-schema.mjs from migrations/*.sql. Do not edit.\n' +
    'export const MIGRATIONS = ' + JSON.stringify(migrations.map(({ version, file, statements }) => ({ version, file, statements })), null, 2) + '\n'
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, 'src', 'schema_sql.js')
  fs.writeFileSync(out, renderSchemaModule(readMigrations()))
  console.log('Wrote src/schema_sql.js')
}
